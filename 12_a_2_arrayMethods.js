
let arr = [0, 1, 2, 3, 4, 5, 6];
//1) PUSH METHOD
arr.push(7);
console.log("arr.push(7); " + arr);


//2) POP METHOD
arr.pop(); //No argument Needed
console.log("now arr = " + arr);
console.log("arr.pop(); " + arr);


//3) unshift Add argument/ element in starting
arr.unshift(10);
console.log(arr);


//4) Shift remove 1st element
arr.shift();
console.log(arr);
